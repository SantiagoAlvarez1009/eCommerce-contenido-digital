from django.db import models
from django.contrib.auth.models import AbstractUser, BaseUserManager


class UserManager(BaseUserManager):
    use_in_migrations = True

    def _create_user(self, email, password, **extra_fields):
        if not email:
            raise ValueError('El correo es obligatorio.')
        email = self.normalize_email(email).lower()
        user  = self.model(email=email, **extra_fields)
        user.set_password(password)
        user.save(using=self._db)
        return user

    def create_user(self, email, password=None, **extra_fields):
        extra_fields.setdefault('is_staff'    , False)
        extra_fields.setdefault('is_superuser', False)
        return self._create_user(email, password, **extra_fields)

    def create_superuser(self, email, password=None, **extra_fields):
        extra_fields.setdefault('is_staff'    , True)
        extra_fields.setdefault('is_superuser', True)
        extra_fields.setdefault('role'        , User.Role.ADMIN)
        return self._create_user(email, password, **extra_fields)


class User(AbstractUser):
    class Role(models.TextChoices):
        CLIENT   = 'cliente'  , 'Cliente'
        OPERATOR = 'operador' , 'Operador'
        ADMIN    = 'admin'    , 'Administrador'

    class Status(models.TextChoices):
        ACTIVE   = 'activo'   , 'Activo'
        INACTIVE = 'inactivo' , 'Inactivo'

    username = None
    email = models.EmailField(
        unique = True
    )
    # Hash generated by Django (AbstractBaseUser.password), stored in column password_hash.
    password = models.CharField(
        max_length = 128,
        db_column  = 'password_hash'
    )
    name = models.CharField(
        max_length = 50
    )
    role = models.CharField(
        max_length = 20,
        choices    = Role.choices,
        default    = Role.CLIENT
    )
    status = models.CharField(
        max_length = 20,
        choices    = Status.choices,
        default    = Status.ACTIVE
    )
    created_at = models.DateTimeField(
        auto_now_add = True
    )

    objects = UserManager()

    USERNAME_FIELD  = 'email'
    REQUIRED_FIELDS = ['name']

    def __str__(self):
        return self.email

    @property
    def is_client(self):
        return self.role == self.Role.CLIENT

    @property
    def is_operator(self):
        return self.role == self.Role.OPERATOR

    @property
    def is_admin_role(self):
        return self.role == self.Role.ADMIN

    def set_enabled(self, enabled):
        """Enable or disable the account, keeping status and is_active in sync."""
        self.is_active = enabled
        self.status    = self.Status.ACTIVE if enabled else self.Status.INACTIVE
        self.save(update_fields=['is_active', 'status'])
