"""
Insertion and recovery of the fingerprint inside the distributed content.
Supports PNG (LSB), TXT (Zero-Width Characters), and PDF (Render mode 3 + Metadata)
"""
import re
from io import BytesIO

from PIL                 import Image
from pypdf               import PdfReader, PdfWriter
from pypdf.generic       import ContentStream, DictionaryObject, NameObject
from stegano             import lsb

PDF_MAGIC = b'%PDF-'
PNG_MAGIC = b'\x89PNG\r\n\x1a\n'

# Zero-width characters used for plain text
ZW_SEP = '‍'  # Invisible separator
ZW_0   = '​'  # Bit 0
ZW_1   = '‌'  # Bit 1

# PDF: custom metadata key and resource name of the font used by the invisible text
PDF_METADATA_KEY = '/Fingerprint'
PDF_FONT_NAME    = '/FPFont'

# Format generated by downloads.services.new_fingerprint_value()
FINGERPRINT_PATTERN = re.compile(r'FP-[0-9A-F]{24}')


class FingerprintError(Exception):
    """The fingerprint could not be inserted into the file."""


def detect_format(data):
    """Return 'pdf', 'png', 'txt' or None, based on the content (not the file name)."""
    if data.startswith(PDF_MAGIC):
        return 'pdf'
    if data.startswith(PNG_MAGIC):
        return 'png'
    try:
        data.decode('utf-8')
        return 'txt'
    except UnicodeDecodeError:
        return None


def embed(data, fingerprint):
    """Return a copy of `data` with `fingerprint` inserted in its content."""
    kind = detect_format(data)
    embedders = {'pdf': _embed_pdf, 'png': _embed_png, 'txt': _embed_text}
    if kind not in embedders:
        raise FingerprintError('Formato de archivo no soportado para fingerprinting.')
    try:
        marked = embedders[kind](data, fingerprint)
    except FingerprintError:
        raise
    except Exception as exc:
        raise FingerprintError(f'No se pudo insertar el fingerprint en el archivo {kind}.') from exc

    # Never deliver a copy whose fingerprint cannot be recovered.
    if extract(marked) != fingerprint:
        raise FingerprintError('El fingerprint no se pudo verificar en la copia generada.')
    return marked


def extract(data):
    """Recover the fingerprint from a copy, or None if it has none."""
    extractors = {'pdf': _extract_pdf, 'png': _extract_png, 'txt': _extract_text}
    extractor  = extractors.get(detect_format(data))
    if extractor is None:
        return None
    try:
        return extractor(data)
    except Exception:
        return None


# TXT

def _embed_text(data, fingerprint):
    text      = data.decode('utf-8')
    bits      = ''.join(format(ord(c), '08b') for c in fingerprint)
    invisible = ZW_SEP + ''.join(ZW_1 if b == '1' else ZW_0 for b in bits)
    return (text + invisible).encode('utf-8')


def _extract_text(data):
    text = data.decode('utf-8')
    if ZW_SEP not in text:
        return None
    bits = ''.join('1' if c == ZW_1 else '0' for c in text.split(ZW_SEP)[-1] if c in (ZW_0, ZW_1))
    if not bits:
        return None
    return ''.join(chr(int(bits[i:i + 8], 2)) for i in range(0, len(bits) - 7, 8))


# PDF

def _helvetica():
    return DictionaryObject({
        NameObject('/Type')    : NameObject('/Font'),
        NameObject('/Subtype') : NameObject('/Type1'),
        NameObject('/BaseFont'): NameObject('/Helvetica'),
    })


def _add_invisible_text(writer, page, text):
    """Append `text` to the page with render mode 3 (neither filled nor stroked: invisible)."""
    resources = page.setdefault(NameObject('/Resources'), DictionaryObject()).get_object()
    fonts     = resources.setdefault(NameObject('/Font'), DictionaryObject()).get_object()
    fonts[NameObject(PDF_FONT_NAME)] = writer._add_object(_helvetica())

    current  = page.get_contents()
    original = current.get_data() if current is not None else b''
    # q ... Q isolates the original graphics state so our text is drawn at a known position.
    marker   = f'BT {PDF_FONT_NAME} 1 Tf 3 Tr 1 1 Td ({text}) Tj ET\n'.encode('ascii')
    contents = ContentStream(None, writer)
    contents.set_data(b'q\n' + original + b'\nQ\n' + marker)
    page.replace_contents(contents)


def _embed_pdf(data, fingerprint):
    if not FINGERPRINT_PATTERN.fullmatch(fingerprint):
        raise FingerprintError('Valor de fingerprint invalido para PDF.')
    reader = PdfReader(BytesIO(data))
    if reader.is_encrypted:
        raise FingerprintError('No se puede marcar un PDF cifrado.')
    writer = PdfWriter(clone_from=reader)
    for page in writer.pages:
        _add_invisible_text(writer, page, fingerprint)
    writer.add_metadata({PDF_METADATA_KEY: fingerprint})
    output = BytesIO()
    writer.write(output)
    return output.getvalue()


def _extract_pdf(data):
    reader = PdfReader(BytesIO(data))
    # 1. Metadata (fast path)
    value = (reader.metadata or {}).get(PDF_METADATA_KEY)
    if value and FINGERPRINT_PATTERN.fullmatch(str(value)):
        return str(value)
    # 2. Invisible text: survives when the metadata is stripped or the pages are copied
    for page in reader.pages:
        match = FINGERPRINT_PATTERN.search(page.extract_text() or '')
        if match:
            return match.group(0)
    return None


# PNG

def _embed_png(data, fingerprint):
    image = Image.open(BytesIO(data))
    if image.mode not in ('RGB', 'RGBA'):
        image = image.convert('RGB')
    marked = lsb.hide(image, fingerprint)
    output = BytesIO()
    marked.save(output, format='PNG')
    return output.getvalue()


def _extract_png(data):
    return lsb.reveal(Image.open(BytesIO(data))) or None